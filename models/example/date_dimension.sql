WITH CTE AS (
select TO_TIMESTAMP(STARTED_AT) as STARTED_AT,
DATE(TO_TIMESTAMP(STARTED_AT)) as DATE_STARTED_AT,
HOUR(TO_TIMESTAMP(STARTED_AT)) as HOUR_STARTED_AT,
DAYNAME(TO_TIMESTAMP(STARTED_AT)),
CASE 
    WHEN DAYNAME(TO_TIMESTAMP(STARTED_AT)) in ('Sat', 'Sun')
        THEN 'WEEKEND'
    ELSE 'WEEKDAY'
END
AS DAY_TYPE,
MONTH(TO_TIMESTAMP(STARTED_AT)) as MONTH_STARTED_AT,
CASE 
    WHEN MONTH(TO_TIMESTAMP(STARTED_AT)) in (12, 1, 2)
        THEN 'WINTER'
    WHEN MONTH(TO_TIMESTAMP(STARTED_AT)) in (3, 4, 5)
        THEN 'SPRING'
    WHEN MONTH(TO_TIMESTAMP(STARTED_AT)) in (6, 7, 8)
        THEN 'SUMMER'
    ELSE 'AUTUMN'
END 
as STATION_OF_THE_YEAR
from 
{{ source('another_demo', 'BIKE') }}
where STARTED_AT != 'started_at'
)

select * from CTE